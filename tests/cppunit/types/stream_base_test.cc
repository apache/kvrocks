#include <gtest/gtest.h>

#include "types/redis_stream_base.h"

TEST(StreamEntryIDTest, IncrementPreservesExhaustedID) {
  for (const auto id : {redis::StreamEntryID::Maximum(), redis::StreamEntryID{UINT64_MAX, 0},
                        redis::StreamEntryID{UINT64_MAX, UINT64_MAX}}) {
    auto next = id;
    const auto status = redis::IncrementStreamEntryID(&next);
    EXPECT_FALSE(status.IsOK());
    EXPECT_EQ(next, id);
  }
}

TEST(StreamEntryIDTest, IncrementReachesMaximum) {
  auto id = redis::StreamEntryID::Maximum();
  --id.seq;
  ASSERT_TRUE(redis::IncrementStreamEntryID(&id).IsOK());
  EXPECT_EQ(id, redis::StreamEntryID::Maximum());
}

TEST(StreamEntryIDTest, IncrementRollsSequenceIntoTimestamp) {
  redis::StreamEntryID id{UINT64_MAX - 2, UINT64_MAX};
  ASSERT_TRUE(redis::IncrementStreamEntryID(&id).IsOK());
  EXPECT_EQ(id, (redis::StreamEntryID{UINT64_MAX - 1, 0}));
}

TEST(StreamEntryIDTest, AutoGenerationRejectsExhaustedID) {
  redis::AutoGeneratedEntryID strategy;
  for (const auto id : {redis::StreamEntryID::Maximum(), redis::StreamEntryID{UINT64_MAX, 0},
                        redis::StreamEntryID{UINT64_MAX, UINT64_MAX}}) {
    redis::StreamEntryID next;
    const auto status = strategy.GenerateID(id, &next);
    EXPECT_FALSE(status.IsOK());
    EXPECT_EQ(next, id);
  }
}
